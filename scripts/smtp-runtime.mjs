// Offline derivation after `composer install --no-dev --no-plugins --no-scripts`.
// No credentials; only these four upstream files may enter the private runtime.
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('..',import.meta.url));
const sha=b=>createHash('sha256').update(b).digest('hex');
const lock=JSON.parse(fs.readFileSync(path.join(root,'composer.lock')));
if(lock.packages.length!==1 || lock.packages[0].name!=='phpmailer/phpmailer' || lock.packages[0].version!=='v7.1.1')throw Error('Review the SMTP dependency lock');
const files=['src/Exception.php','src/PHPMailer.php','src/SMTP.php','LICENSE'];
const hashes=Object.fromEntries(files.map(f=>{
 const p=path.join(root,'vendor/phpmailer/phpmailer',f);
 if(!fs.lstatSync(p).isFile() || fs.lstatSync(p).isSymbolicLink())throw Error('Unsafe runtime source');
 return [f,sha(fs.readFileSync(p))];
}));
const identity=sha(JSON.stringify(hashes));
const manifest={version:'7.1.1',reference:lock.packages[0].source.reference,license:'LGPL-2.1-only',identity,files:hashes};
const php='<'+'?php\ndeclare(strict_types=1);\n// Generated by scripts/smtp-runtime.mjs; no secrets.\nreturn json_decode('+JSON.stringify(JSON.stringify(manifest))+', true, 8, JSON_THROW_ON_ERROR);\n';
const target=path.join(root,'api/smtp-manifest.php');
if(process.argv.includes('--record'))fs.writeFileSync(target,php);
else if(fs.readFileSync(target,'utf8')!==php)throw Error('PHPMailer hashes differ from the reviewed manifest');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'data/apartments.json'))).map(l=>Object.fromEntries(['id','number','bedrooms','area_m2','floor','price_rub','snapshot_date'].map(k=>[k,l[k]])));
const catalogPHP='<'+'?php\ndeclare(strict_types=1);\n// Generated from data/apartments.json; authoritative server snapshot.\nreturn json_decode('+JSON.stringify(JSON.stringify(catalog))+', true, 8, JSON_THROW_ON_ERROR);\n';
const catalogPath=path.join(root,'api/lead-catalog.php');
if(process.argv.includes('--record'))fs.writeFileSync(catalogPath,catalogPHP);
else if(fs.readFileSync(catalogPath,'utf8')!==catalogPHP)throw Error('Server catalog differs from published data');
// A private installation fixture, also used as the exact private package allowlist.
const output=path.join(root,'.release-output/smtp-runtime',identity);
fs.mkdirSync(output,{recursive:true,mode:0o700});
for(const f of files){const dest=path.join(output,f);fs.mkdirSync(path.dirname(dest),{recursive:true,mode:0o700});fs.copyFileSync(path.join(root,'vendor/phpmailer/phpmailer',f),dest);fs.chmodSync(dest,0o600);}
fs.writeFileSync(path.join(output,'manifest.json'),JSON.stringify(manifest,null,2)+'\n',{mode:0o600});
console.log(JSON.stringify({identity,version:manifest.version,files:files.length,privateRuntime:output}));
